tag_glossary = {
    "attack": ["<your_insturction id='Turn-{idx}'>\n", "\n</your_insturction id='Turn-{idx}'>\n"],
    "simulate": ["<partner_insturction id='Turn-{idx}'>\n", "\n</partner_insturction id='Turn-{idx}'>\n"]
}


def construct_attack_input(batch_sample, conversation_history, mode="attack", candidate_prompts=None):
    conversation_history_str_start = "<conversation_history>\n"
    conversation_history_str_end = "\n</conversation_history>\n"
    # print("batch sample: ", batch_sample['base_prompt'])
    obj = batch_sample['base_prompt'][0]
    jail_prompt = batch_sample['prompt'][0]

    if len(conversation_history) > 0:
        conversation_history_str = ""
        for i, turn in enumerate(conversation_history):
            conversation_history_str += tag_glossary[mode][0].format(idx=i+1) + turn['user'] + tag_glossary[mode][1].format(idx=i+1)
            conversation_history_str += f"<victim_LLM_response id='Turn-{i+1}'>\n" + turn['assistant'] + f"\n</victim_LLM_response id='Turn-{i+1}'>\n"
        conversation_history_str = conversation_history_str_start + conversation_history_str + conversation_history_str_end 
    else:
        conversation_history_str = conversation_history_str_start + conversation_history_str_end 


    prompt = "<malicious_objective>\n" + obj + "\n</malicious_objective>\n"
    prompt += "<jailbreak_prompt>\n" + jail_prompt + "\n</jailbreak_prompt>\n"
    prompt += conversation_history_str
    if mode == "simulate" and candidate_prompts != None:
        prompt += "<partner_instruction>\n" + candidate_prompts + "\n</partner_instruction>\n"
    formated_inputs = {
        "prompt": [prompt],
        "objective": obj,
        "jailbreak_prompt": jail_prompt,
    }
    
    return conversation_history_str, formated_inputs

